class Ticket{
    String Ticket_id;
    String name;
    int age;
    String gender;
    char berth;

    public Ticket(String Ticket_id , String name,int age,String gender,char berth) {
        this.Ticket_id = Ticket_id;
        this.name = name;
        this.age = age;
        this.gender = gender;
        this.berth = berth;
    }
}